let currentLang = 'en';

function detectInitialLanguage() {
  try {
    const saved = (typeof settings !== 'undefined' && settings.lang) ? settings.lang : localStorage.getItem('sectorDefenseTD_lang');
    if (saved && SUPPORTED_LANGUAGES[saved]) return saved;
    const nav = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    if (nav.startsWith('zh-tw') || nav.startsWith('zh-hk')) return 'tw';
    const short = nav.split('-')[0];
    if (SUPPORTED_LANGUAGES[short]) return short;
  } catch (e) {}
  return 'en';
}

function t(key, params) {
  const dict = I18N_DICT[currentLang] || I18N_DICT.en;
  let str = (dict && dict[key] !== undefined) ? dict[key] : (I18N_DICT.en[key] || key);
  if (params && typeof params === 'object') {
    Object.keys(params).forEach(k => {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), params[k]);
    });
  }
  return str;
}

function applyStaticTranslations() {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = currentLang;
  document.documentElement.dir = (currentLang === 'ar') ? 'rtl' : 'ltr';

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key);
  });
}

function setLanguage(langCode, persist = true) {
  if (!SUPPORTED_LANGUAGES[langCode]) langCode = 'en';
  currentLang = langCode;
  if (typeof settings !== 'undefined') settings.lang = langCode;
  if (persist) {
    try { localStorage.setItem('sectorDefenseTD_lang', langCode); } catch (e) {}
    if (typeof saveGameSoon === 'function') saveGameSoon();
  }
  applyStaticTranslations();

  const langSelect = document.getElementById('settingLangSelect');
  if (langSelect && langSelect.value !== langCode) {
    langSelect.value = langCode;
  }

  // Перерисовываем открытые динамические экраны
  if (typeof updateUI === 'function' && typeof window.__gameBooted !== 'undefined' && window.__gameBooted) {
    try { updateUI(); } catch (e) {}
  }
  if (typeof updateModeSwitcherUI === 'function' && typeof gameState !== 'undefined' && gameState === 'LEVELS') {
    try { updateModeSwitcherUI(); renderLevelsGrid(); } catch (e) {}
  }
}

function populateLanguageDropdown() {
  const select = document.getElementById('settingLangSelect');
  if (!select) return;
  select.innerHTML = '';
  Object.keys(SUPPORTED_LANGUAGES).forEach(code => {
    const opt = document.createElement('option');
    opt.value = code;
    opt.textContent = SUPPORTED_LANGUAGES[code];
    if (code === currentLang) opt.selected = true;
    select.appendChild(opt);
  });
}

