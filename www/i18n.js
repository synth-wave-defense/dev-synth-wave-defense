// [I18.D]
function detectInitialLanguage() {
  try {
    const saved = (typeof settings !== 'undefined' && settings.lang) ? settings.lang : localStorage.getItem('sectorDefenseTD_lang');
    if (saved && SUPPORTED_LANGUAGES[saved]) return saved;
    const nav = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    const short = nav.split('-')[0];
    if (SUPPORTED_LANGUAGES[short]) return short;
  } catch (e) {}
  return 'en';
}

// [I18.E]
function t(key, params) {
  const dict = I18N_DICT[currentLang] || I18N_DICT.en;
  const resolvedKey = (dict && dict[key] !== undefined) ? key : (KEY_ALIASES[key] || key);
  let str = (dict && dict[resolvedKey] !== undefined)
    ? dict[resolvedKey]
    : (I18N_DICT.en[resolvedKey] !== undefined ? I18N_DICT.en[resolvedKey] : '');

  if (!str) return '';

  const p = Object.assign({}, params);
  if (key === 'not_enough_diamonds_30' && p.cost === undefined) p.cost = 30;
  if (p.t !== undefined && p.n === undefined) p.n = p.t;
  if (p.n !== undefined && p.t === undefined) p.t = p.n;

  // Прямая поддержка плейсхолдеров обоих форматов: {d}/{icon} и {dia}/{prism}
  if (p.d !== undefined && p.dia === undefined) p.dia = p.d;
  if (p.dia !== undefined && p.d === undefined) p.d = p.dia;
  if (p.p !== undefined && p.prism === undefined) p.prism = p.p;
  if (p.prism !== undefined && p.p === undefined) p.p = p.prism;

  Object.keys(p).forEach(k => {
    str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), p[k]);
  });
  return str;
}

// [I18.F]
function applyStaticTranslations() {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = currentLang;
  document.documentElement.dir = (currentLang === 'ar') ? 'rtl' : 'ltr';

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      const val = t(key);
      if (val) el.textContent = val;
    }
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (key) {
      const val = t(key);
      if (val) el.innerHTML = val;
    }
  });
}

// [I18.G]
function setLanguage(langCode, persist = true) {
  if (!SUPPORTED_LANGUAGES[langCode]) langCode = 'en';
  currentLang = langCode;
  if (typeof settings !== 'undefined') settings.lang = langCode;
  if (persist) {
    try { localStorage.setItem('sectorDefenseTD_lang', langCode); } catch (e) {}
    if (typeof saveGameSoon === 'function') saveGameSoon();
  }
  applyStaticTranslations();

  const langSelect = document.getElementById('settingLangSelect');
  if (langSelect && langSelect.value !== langCode) {
    langSelect.value = langCode;
  }
  if (typeof updateLanguageSelectDropdown === 'function') {
    updateLanguageSelectDropdown('settingLangSelect');
  }

  // Перерисовываем открытые динамические экраны и виджеты
  if (typeof window !== 'undefined' && window.__gameBooted) {
    try {
      if (typeof updateUI === 'function') updateUI();
      if (typeof updateUpgradeButtonsLock === 'function') updateUpgradeButtonsLock();
      if (typeof updateBpProgressUI === 'function') updateBpProgressUI();
      if (typeof renderShopScreen === 'function' && typeof gameState !== 'undefined' && gameState === 'SHOP') renderShopScreen();
      if (typeof renderUpgradeTree === 'function' && typeof gameState !== 'undefined' && gameState === 'UPGRADES') renderUpgradeTree();
      if (typeof renderBattlePassScreen === 'function' && typeof gameState !== 'undefined' && gameState === 'BATTLE_PASS') renderBattlePassScreen();
      if (typeof renderLevelsGrid === 'function' && typeof gameState !== 'undefined' && gameState === 'LEVELS') renderLevelsGrid();
      if (typeof updateModeSwitcherUI === 'function') updateModeSwitcherUI();
      if (typeof updatePaletteSelectDropdown === 'function') {
        updatePaletteSelectDropdown('settingPaletteSelect');
        updatePaletteSelectDropdown('bpPaletteSelect');
      }
    } catch (e) {}
  }
}

// [I18.GA]
function populateLanguageDropdown(selectId = 'settingLangSelect') {
  const select = document.getElementById(selectId);
  if (!select) return;

  select.innerHTML = '';
  Object.keys(SUPPORTED_LANGUAGES).forEach(code => {
    const opt = document.createElement('option');
    opt.value = code;
    opt.textContent = SUPPORTED_LANGUAGES[code];
    select.appendChild(opt);
  });

  select.value = currentLang;

  // Если слушатель ещё не был привязан — привязываем переключение
  if (!select.dataset.i18nBound) {
    select.addEventListener('change', (e) => {
      setLanguage(e.target.value, true);
    });
    select.dataset.i18nBound = 'true';
  }

  if (typeof updateLanguageSelectDropdown === 'function') {
    updateLanguageSelectDropdown(selectId);
  }
}

